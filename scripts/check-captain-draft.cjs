const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const exportsObject = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/app/utils/captain-draft.ts','utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{exports:exportsObject,require:()=>({}),Set});
const {captainDraftState: derive} = exportsObject;
const people = ['a','b','c','d','e','f','g','h'];
const event = {attendances:Object.fromEntries(people.map(playerId=>[playerId,{playerId,playsSoccer:true}])),captainDraft:{nextTeamId:'team_2'},teams:{teams:[{id:'team_1',captainPlayerId:'a',playerIds:['a']},{id:'team_2',captainPlayerId:'b',playerIds:['b']}]}};
assert.equal(derive(event).nextTeam.id,'team_2');
assert.equal(derive(event).available.length,6);
assert.equal(derive(event).ready,false);
event.teams.teams[1].playerIds.push('c');
assert.equal(derive(event).nextTeam.id,'team_1','shorter team takes next pick');
event.teams.teams[0].playerIds=['a','d','e','f'];
event.teams.teams[1].playerIds=['b','c','g','h'];
assert.equal(derive(event).ready,true);
event.attendances.i={playerId:'i',playsSoccer:true};
assert.equal(derive(event).ready,false,'late arrival reopens selection');
assert.equal(derive(event).available[0],'i');
event.teams.teams[1].playerIds.push('i');
assert.equal(derive(event).ready,true,'odd player total is allowed with balanced sides');
event.attendances.d.playsSoccer=false;
assert.equal(derive(event).departed[0],'d');
assert.equal(derive(event).ready,false,'dropout blocks match start');
event.teams.teams[0].playerIds=event.teams.teams[0].playerIds.filter(id=>id!=='d');
assert.equal(derive(event).ready,false,'3 vs 5 is not ready');
event.teams.teams[1].playerIds=event.teams.teams[1].playerIds.filter(id=>id!=='i');
event.teams.teams[0].playerIds.push('i');
assert.equal(derive(event).ready,true);
event.teams.teams[0].captainPlayerId='missing';
assert.equal(derive(event).ready,false,'captain must play for own team');
console.log('Captain draft: turns, minimum, late arrivals, dropouts and balance passed.');
